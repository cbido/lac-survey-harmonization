"""Basic checks on the ingested files, written to docs/ingest_checks.md.

For every survey with a Parquet file: persons, households, the sum of the expansion
factor, and the weighted share of persons the statistics office itself classifies as
poor. The point is to compare the files with published figures before anything is
built on them.

Usage:
    python validate/ingest_report.py
"""
from __future__ import annotations

from pathlib import Path

import duckdb
import yaml

# Chile: serie revisada publicada por el MDSF en los resultados de Casen 2022 (personas, %)
PUBLISHED = {"CHL_2015": 11.2, "CHL_2017": 8.5, "CHL_2020": 10.7, "CHL_2022": 6.5}


def main() -> None:
    with open("config/surveys.yml", encoding="utf-8") as f:
        surveys = yaml.safe_load(f)["surveys"]
    con = duckdb.connect()
    lines = [
        "# Checks on ingested files",
        "",
        "Generated by `validate/ingest_report.py` from the Parquet files in `data/parquet/`.",
        "",
        "| survey | persons | households | variables | weighted population | extreme poverty % | poverty % | published % |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for survey, spec in surveys.items():
        checks = spec.get("checks")
        if not checks:
            continue
        path = Path("data/parquet") / f"{checks['table']}.parquet"
        if not path.exists():
            continue
        weight, src = spec["design"]["weight"], f"read_parquet('{path}')"
        persons, households, population = con.execute(
            f"SELECT COUNT(*), COUNT(DISTINCT {checks['household_id']}), SUM({weight}) FROM {src}"
        ).fetchone()
        n_vars = len(con.execute(f"DESCRIBE SELECT * FROM {src}").fetchall())
        extreme, poor = con.execute(
            f"""SELECT 100.0 * SUM(CASE WHEN {checks['extreme']} THEN {weight} END) / SUM({weight}),
                       100.0 * SUM(CASE WHEN {checks['poor']} THEN {weight} END) / SUM({weight})
                FROM {src} WHERE ({checks['poor']}) IS NOT NULL"""
        ).fetchone()
        lines.append(
            f"| {survey} | {persons:,} | {households:,} | {n_vars} | {population:,.0f} | {extreme:.1f} | {poor:.1f} | {PUBLISHED.get(survey, '')} |"
        )
    lines += [
        "",
        "Poverty is the weighted share of persons classified as poor by each statistics",
        "office's own variable (`pobreza` in Casen, `p0` and `pext0` in Bolivia's Encuesta de",
        "Hogares), using the expansion factor named in `config/surveys.yml`.",
        "",
        "Chile: the 2022 figure matches the published rate. For 2015, 2017 and 2020 the files",
        "are the original releases, and the last column is the revised series printed in the",
        "ministry's Casen 2022 results, so small differences are expected. Checking each",
        "original-release figure against the report published with that round is still pending.",
        "",
        "Bolivia: the published rates have not been looked up yet. The files also carry a",
        "second expansion factor, `factor_rev2025`, adjusted to the 2025 population projections.",
        "",
    ]
    Path("docs").mkdir(exist_ok=True)
    Path("docs/ingest_checks.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[4:16]))


if __name__ == "__main__":
    main()
